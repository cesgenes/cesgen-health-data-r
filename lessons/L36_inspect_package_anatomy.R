# -----------------------------------------------------------------------------
# 1. Helpers: read one field of DESCRIPTION and summarise an installed package
# -----------------------------------------------------------------------------
# Return a DESCRIPTION field as one tidy string, or "(none)" if it is absent
description_field <- function(desc, name) {
  value <- desc[[name]]
  if (is.null(value) || is.na(value)) return("(none)")
  gsub("\\s+", " ", value)
}

# Summarise an installed package in one row; NULL if it is not installed
summarise_package <- function(pkg) {
  if (!requireNamespace(pkg, quietly = TRUE)) return(NULL)
  s3_table <- tryCatch(getNamespaceInfo(pkg, "S3methods"), error = function(e) NULL)
  data_items <- tryCatch(utils::data(package = pkg)$results[, "Item"],
                         error = function(e) character(0))
  vignette_items <- tryCatch(utils::vignette(package = pkg)$results[, "Item"],
                             error = function(e) character(0))
  data.frame(
    package = pkg,
    version = as.character(utils::packageVersion(pkg)),
    n_exports = length(getNamespaceExports(pkg)),
    n_s3_methods = if (is.null(s3_table)) NA_integer_ else nrow(s3_table),
    n_datasets = length(data_items),
    n_vignettes = length(vignette_items),
    stringsAsFactors = FALSE
  )
}

# -----------------------------------------------------------------------------
# 2. The skeleton of a SOURCE package (what you write) - for reference
# -----------------------------------------------------------------------------
source_skeleton <- data.frame(
  path = c("DESCRIPTION", "NAMESPACE", "R/", "man/", "tests/testthat/",
           "vignettes/", "data/", "data-raw/", "inst/"),
  holds = c("name, version, authors, licence, dependencies",
            "what is exported and imported (generated by roxygen2)",
            "the functions, with roxygen comments",
            "help pages (generated from the roxygen comments)",
            "automated tests",
            "long-form tutorials that run code",
            "example data saved as .rda (ready to load)",
            "the script that builds the data (not shipped)",
            "files copied as they are: CITATION, extdata/"),
  you_write_it = c("yes", "no", "yes", "no", "yes", "yes", "no", "yes", "yes"),
  stringsAsFactors = FALSE
)
cat("\nSource package skeleton (you_write_it = 'no' means generated):\n")
print(source_skeleton, row.names = FALSE)

# -----------------------------------------------------------------------------
# 3. Look inside installed packages
# -----------------------------------------------------------------------------
packages_to_inspect <- c("stats", "nlme", "PITS")
summaries <- lapply(packages_to_inspect, summarise_package)
names(summaries) <- packages_to_inspect

not_installed <- names(summaries)[vapply(summaries, is.null, logical(1))]
if (length(not_installed) > 0) {
  message("Not installed, skipped: ", paste(not_installed, collapse = ", "),
          ". To add PITS: install.packages(\"PITS\") (check CRAN availability).")
}
anatomy <- do.call(rbind, summaries[!vapply(summaries, is.null, logical(1))])
cat("\nInstalled packages at a glance:\n")
print(anatomy, row.names = FALSE)

# Top-level entries of an INSTALLED package differ from the source skeleton:
# R code is compiled into a database, help pages are converted, etc.
inspect_installed <- function(pkg) {
  if (!requireNamespace(pkg, quietly = TRUE)) return(invisible(NULL))
  path <- system.file(package = pkg)
  desc <- utils::packageDescription(pkg)
  cat("\n---", pkg, "---\n")
  cat("Title:   ", description_field(desc, "Title"), "\n")
  cat("Version: ", description_field(desc, "Version"), "\n")
  cat("Licence: ", description_field(desc, "License"), "\n")
  cat("Imports: ", description_field(desc, "Imports"), "\n")
  cat("Top-level entries of the installed package:\n  ",
      paste(list.files(path), collapse = ", "), "\n")
  exports <- sort(getNamespaceExports(pkg))
  cat("First exported names:", paste(utils::head(exports, 8), collapse = ", "), "\n")
  invisible(path)
}
for (pkg in c("nlme", "PITS")) inspect_installed(pkg)

