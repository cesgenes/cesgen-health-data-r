# Lesson 39: Publish, cite and maintain
# Goal:     turn the release checklist into code: check that a package folder
#           has the standard files, that DESCRIPTION is complete, that the
#           version in NEWS.md and CITATION agrees with DESCRIPTION, and that
#           no data file has identifier-like column names.
# Inputs:   a package folder (default: templates/mini_health_package)
# Outputs:  printed tables; output/L39_release_checklist.csv
# Packages: base R only (utils). Uses R/helpers_general.R for the identifier scan.
# Data:     SIMULATED for teaching purposes; no real people.
# Educational material; it does not replace a health professional.
# Run from the repository root (RStudio project).
# =============================================================================

source("R/helpers_general.R")
dir.create("output", showWarnings = FALSE)

# -----------------------------------------------------------------------------
# 1. The files a health analysis package should have
# -----------------------------------------------------------------------------
# `any_of` lists alternative file names; a trailing "/" means a folder
release_items <- data.frame(
  item = c("DESCRIPTION", "NAMESPACE", "R code", "Licence", "Help pages (man/)",
           "README", "NEWS", "Tests", ".Rbuildignore", ".gitignore",
           "Vignettes", "CITATION", "CRAN comments", "GitHub Actions check"),
  any_of = c("DESCRIPTION", "NAMESPACE", "R/", "LICENSE|LICENSE.md", "man/",
             "README.md|README.Rmd", "NEWS.md", "tests/testthat/", ".Rbuildignore",
             ".gitignore", "vignettes/", "inst/CITATION", "cran-comments.md",
             ".github/workflows/"),
  level = c("required", "required", "required", "required", "generated",
            "recommended", "recommended", "recommended", "recommended", "recommended",
            "optional", "optional", "optional", "optional"),
  hint = c("name, version, authors, licence",
           "generated by devtools::document()",
           "at least one .R file",
           "state the licence; MIT is used by PITS",
           "run devtools::document() to create it",
           "what it does, how to install, a short example, the scope and limits",
           "one entry per version, newest first",
           "testthat tests; essential when the output informs decisions",
           "keeps data-raw/, LICENSE.md and similar out of the built package",
           "keeps local files out of version control",
           "long-form tutorials (PITS has three)",
           "how to cite the package (and the paper, when it exists)",
           "only needed for a CRAN submission",
           "e.g. usethis::use_github_action(\"check-standard\")"),
  stringsAsFactors = FALSE
)

# TRUE if at least one alternative exists (and, for folders, is not empty)
item_present <- function(path, any_of) {
  options <- strsplit(any_of, "|", fixed = TRUE)[[1]]
  any(vapply(options, function(rel) {
    full <- file.path(path, rel)
    if (grepl("/$", rel)) {
      dir.exists(full) && length(list.files(full, recursive = TRUE)) > 0
    } else {
      file.exists(full)
    }
  }, logical(1)))
}

# -----------------------------------------------------------------------------
# 2. Content checks: DESCRIPTION fields and version consistency
# -----------------------------------------------------------------------------
read_description <- function(path) {
  file <- file.path(path, "DESCRIPTION")
  if (!file.exists(file)) return(NULL)
  read.dcf(file)[1, ]
}

# First version-like string in a character vector, or NA
first_version <- function(lines) {
  hit <- regmatches(lines, regexpr("[0-9]+\\.[0-9]+\\.[0-9]+(\\.[0-9]+)?", lines))
  if (length(hit) == 0) NA_character_ else hit[1]
}

check_release <- function(path) {
  stopifnot(dir.exists(path))

  files <- release_items
  files$present <- vapply(files$any_of, item_present, logical(1), path = path)
  files$status <- ifelse(files$present, "ok",
                         ifelse(files$level == "required", "MISSING",
                                ifelse(files$level == "generated", "generate it",
                                       ifelse(files$level == "recommended", "add it", "optional"))))

  desc <- read_description(path)
  wanted <- c("Package", "Title", "Version", "Authors@R", "Description", "License")
  fields <- data.frame(
    field = wanted,
    present = if (is.null(desc)) rep(FALSE, length(wanted)) else
      wanted %in% names(desc) & !is.na(desc[match(wanted, names(desc))]),
    stringsAsFactors = FALSE
  )

  # Version consistency: DESCRIPTION vs the first heading of NEWS.md vs CITATION
  desc_version <- if (is.null(desc) || !"Version" %in% names(desc)) NA_character_ else desc[["Version"]]
  news_file <- file.path(path, "NEWS.md")
  news_version <- if (file.exists(news_file)) {
    headings <- grep("^#", readLines(news_file, warn = FALSE), value = TRUE)
    first_version(headings)
  } else NA_character_
  citation_file <- file.path(path, "inst", "CITATION")
  citation_version <- if (file.exists(citation_file)) {
    first_version(grep("version", readLines(citation_file, warn = FALSE),
                       value = TRUE, ignore.case = TRUE))
  } else NA_character_
  versions <- data.frame(
    source = c("DESCRIPTION", "NEWS.md (first heading)", "inst/CITATION (hard-coded text)"),
    version = c(desc_version, news_version, citation_version),
    stringsAsFactors = FALSE
  )
  versions$agrees <- is.na(versions$version) | versions$version == desc_version

  # Identifier-like column names in CSV files that ship with the package
  csv_files <- list.files(path, pattern = "\\.csv$", recursive = TRUE, full.names = TRUE)
  csv_files <- csv_files[grepl("data-raw|extdata", csv_files)]
  identifier_scan <- do.call(rbind, c(list(data.frame(file = character(0), column = character(0))),
    lapply(csv_files, function(f) {
      hits <- flag_identifier_columns(utils::read.csv(f, nrows = 5))
      if (nrow(hits) == 0) NULL else data.frame(file = f, column = hits$column)
    })))

  list(files = files, fields = fields, versions = versions,
       identifier_scan = identifier_scan, n_csv_scanned = length(csv_files))
}

# -----------------------------------------------------------------------------
# 3. Run it on the template package and report
# -----------------------------------------------------------------------------
package_path <- "templates/mini_health_package"
report <- check_release(package_path)

cat("\nStandard files in", package_path, "\n")
print(report$files[, c("item", "level", "status", "hint")], row.names = FALSE)
cat("\nDESCRIPTION fields:\n")
print(report$fields, row.names = FALSE)
cat("\nVersion consistency:\n")
print(report$versions, row.names = FALSE)
cat("\nCSV files scanned for identifier-like column names:", report$n_csv_scanned,
    "; hits:", nrow(report$identifier_scan), "\n")

n_missing_required <- sum(report$files$status == "MISSING")
cat("\nRequired items missing:", n_missing_required, "\n")
cat("To do before sharing:",
    paste(report$files$item[report$files$status %in% c("generate it", "add it")], collapse = "; "),
    "\n")

# Sanity checks on the template (man/ is generated, so it is expected to be absent)
stopifnot(n_missing_required == 0,
          all(report$fields$present),
          all(report$versions$agrees),
          nrow(report$identifier_scan) == 0)

utils::write.csv(report$files[, c("item", "level", "present", "status")],
                 "output/L39_release_checklist.csv", row.names = FALSE)
cat("Saved: output/L39_release_checklist.csv\n")

